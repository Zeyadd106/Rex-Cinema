export type Lang = 'en' | 'ar';

export const locales: Record<Lang, string> = { en: 'en-US', ar: 'ar-EG' };

export function fmtDay(dateStr: string, lang: Lang): string {
  return new Date(dateStr + 'T12:00:00').toLocaleDateString(locales[lang], { weekday: 'short', day: 'numeric', month: 'short' });
}

export function fmtLongDate(dateStr: string, lang: Lang): string {
  return new Date(dateStr + 'T12:00:00').toLocaleDateString(locales[lang], { day: 'numeric', month: 'long', year: 'numeric' });
}

export function fmtTime12(time: string, lang: Lang): string {
  return new Date(`2000-01-01T${time}`).toLocaleTimeString(locales[lang], { hour: 'numeric', minute: '2-digit', hour12: true }).toLowerCase().replace(' ', '');
}

